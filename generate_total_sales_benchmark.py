"""Generate offline NL2SQL benchmark prompts for total-sales analysis."""

import csv
from pathlib import Path


COMPANIES = [
    "HPCL", "BPCL", "IOCL", "SHELL", "RIL", "ONGC", "OIL",
    "GAIL", "SMA", "CPCL", "MRPL", "NEL", "HMEL",
]
SBUS = ["Retail", "Lubes", "LPG", "NG", "Aviation", "I&C"]
YEARS = ["2023-2024", "2024-2025", "2025-2026"]


def generate_prompts() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    seen: set[str] = set()

    def add(prompt: str, company: str, sbu: str = "", year: str = "") -> None:
        if prompt in seen:
            return
        seen.add(prompt)
        rows.append({
            "id": f"total_sales_{len(rows) + 1:04d}",
            "family": "total_sales",
            "prompt": prompt,
            "company": company,
            "sbu": sbu,
            "fiscal_year": year,
        })

    scoped_templates = [
        "What is total sales for {company} in {sbu} during FY {year}?",
        "Show total sales for {company} in {sbu} for FY {year}.",
        "Give the sales volume for {company} in the {sbu} SBU during {year}.",
    ]
    for company in COMPANIES:
        for sbu in SBUS:
            for year in YEARS:
                for template in scoped_templates:
                    add(template.format(company=company, sbu=sbu, year=year), company, sbu, year)

    for company in COMPANIES:
        for sbu in SBUS:
            add(f"Show sales for {company} in {sbu}.", company, sbu)

    for company in COMPANIES:
        add(f"Give total volume sold by {company}.", company)
        add(f"How much business was generated by {company}?", company)

    return rows


def main() -> None:
    output = Path("data/benchmark_total_sales_prompts.csv")
    rows = generate_prompts()
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)
    print(f"Generated {len(rows)} prompts: {output}")


if __name__ == "__main__":
    main()
